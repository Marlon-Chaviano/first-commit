/** Logos for a kit's tags, without repeats (Next.js and nextjs → one). */
export function logosFor(keys: readonly string[], max = 4): { key: string; icon: SimpleIcon }[] {
  const seen = new Set<string>();
  const out: { key: string; icon: SimpleIcon }[] = [];
  for (const key of keys) {
    const icon = LOGOS[key];
    if (!icon || seen.has(icon.slug)) continue;
    seen.add(icon.slug);
    out.push({ key, icon });
    if (out.length === max) break;
  }
  return out;
}
